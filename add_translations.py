# Insert new keys before the closing `},` of each language block
# Strategy: find `verifiedReviewer: "..."` for each language and append after
for lang, keys in new_keys.items():
    new_entries = "\n" + "\n".join(f'    {k}: "{v}",' for k, v in keys.items())
    # Match the verifiedReviewer line for this language block (with or without trailing comma)
    pattern = r'(    verifiedReviewer: "[^"]*",?\n)(  \},?\n(?:  ' + re.escape(lang[:4]) + '|};))'
    # Simpler: find all verifiedReviewer entries and replace them with themselves + new keys
    # We need to be careful to only modify the right language block
    # Use a state machine approach: find the language key, then find its verifiedReviewer
    lang_start = content.find(f'  {lang}:')
    if lang_start == -1:
        print(f"Could not find language: {lang}")
        continue
    # Find verifiedReviewer after the language start
    vr_start = content.find('    verifiedReviewer:', lang_start)
    if vr_start == -1:
        print(f"Could not find verifiedReviewer for: {lang}")
        continue
    vr_end = content.find('\n', vr_start) + 1
    vr_line = content[vr_start:vr_end]
    
    # Ensure we're inside the right block by checking no other language starts between lang_start and vr_start
    next_lang = content.find('\n  ', lang_start + len(lang) + 3)
    if next_lang < vr_start:
        print(f"Skipping {lang} - verifiedReviewer found after next language block?")
        continue
    
    # Build replacement: verifiedReviewer line (with comma) + new keys
    vr_stripped = vr_line.rstrip()
    if vr_stripped.endswith(','):
        new_vr = vr_line
    else:
        new_vr = vr_stripped + ',\n'
    
    replacement = new_vr + new_entries + "\n"
    content = content[:vr_start] + replacement + content[vr_end:]
    print(f"Updated: {lang}")

with open("frontend/src/app/page.tsx", "w") as f:
    f.write(content)

